// Brings the team's destination content (web/js/data/destinos.js + editorial.js) into the mock API:
// the three extra destinations (Montejo, Tejeda, Teide), their sourced versions of Jerte and the
// Alpujarra, and the editorial texts with cited sources for every destination. Tejera Negra and
// Brihuega keep this app's own real-data computation; only their texts and sources come from here.
// Run from frontend/: node scripts/import_equipo_destinos.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { Ot } = await import(join(root, 'web/js/data/destinos.js'));

const COMPLETOS = ['montejo', 'tejeda', 'teide', 'jerte', 'alpujarra'];
const UMBRALES = { inicio: 0.15, avance: 0.4, pleno: 0.7, final: 0.5 };

// The team marks forecasts built from past years as "climatologia"; this app's contract has no such
// method, so Greenia's reference dates count as provided data and public historical dates as the v0 model.
const metodo = (v) => (v.metodo !== 'climatologia' ? v.metodo : /Greenia/.test(v.fuente) ? 'dato_proporcionado' : 'modelo_v0');

const completos = Ot.filter((d) => COMPLETOS.includes(d.id)).map((d) => ({
  id: d.id, nombre: d.nombre, lugar: d.lugar, provincia: d.provincia, region: d.region, especie: d.especie,
  fenomeno: d.fenomeno, tipo: d.tipo, lat: d.lat, lon: d.lon, color: d.color, ilustracion: d.ilustracion,
  temporada: d.temporada, finTemporada: d.finTemporada, datosReales: d.datosReales, estado: d.estado,
  ventanas: d.ventanas.map((v) => ({ ...v, metodo: metodo(v) })),
  habituales: d.habituales, entradasHasta: d.entradasHasta, generadaEn: d.generadaEn,
  umbrales: d.umbrales ?? UMBRALES, editorial: d.editorial,
}));
const textos = Object.fromEntries(Ot.map((d) => [d.id, { editorial: d.editorial, fuentes: d.fuentes ?? [] }]));

const out = join(root, 'frontend/src/api/mock/datosEquipo.ts');
writeFileSync(
  out,
  `// GENERATED by scripts/import_equipo_destinos.mjs from the team's web/js/data/. Do not edit by hand.\n` +
    `import type { Destino, Editorial } from './tipos';\n\n` +
    `export interface FuenteCitada {\n  nombre: string;\n  url: string | null;\n}\n\n` +
    `/** Destinations taken whole from the team's site. Some forecast windows carry no probability on purpose. */\n` +
    `export const DESTINOS_EQUIPO = ${JSON.stringify(completos, null, 1)} as unknown as Destino[];\n\n` +
    `/** Editorial texts and cited sources for every destination. */\n` +
    `export const TEXTOS_EQUIPO: Record<string, { editorial: Editorial; fuentes: FuenteCitada[] }> = ${JSON.stringify(textos, null, 1)};\n`,
);
console.log('wrote', out, completos.map((d) => d.id).join(', '), '+ texts for', Object.keys(textos).length);
