function fusionar(base, extra) {
  for (const [k, v] of Object.entries(extra))
    v && typeof v == "object" && !Array.isArray(v) && base[k] && typeof base[k] == "object"
      ? fusionar(base[k], v)
      : (base[k] = v);
  return base;
}

